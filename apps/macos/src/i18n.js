const DICTS = { vi, en }

// lang: 'auto' | 'vi' | 'en'. systemLocale ví dụ 'vi-VN', 'en-US' (app.getLocale()).
function resolveLang(lang, systemLocale) {
  if (lang === 'vi' || lang === 'en') return lang
  return String(systemLocale || '').toLowerCase().startsWith('vi') ? 'vi' : 'en'
}

function getStrings(lang, systemLocale) {
  return DICTS[resolveLang(lang, systemLocale)]
}

// Thay {token} trong chuỗi bằng giá trị tương ứng trong `vars`.
function fmt(str, vars) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}

// Map mã lỗi kỹ thuật (renderer.js ERRORS cũ) -> chuỗi đã dịch.
const ERROR_KEYS = {
  NO_CREDENTIALS: 'errNoCredentials',
  NO_TOKEN: 'errNoToken',
  EXPIRED: 'errExpired',
  UNAUTHORIZED: 'errUnauthorized',
  RATE_LIMITED: 'errRateLimited',
  TIMEOUT: 'errTimeout',
  NETWORK: 'errNetwork',
  NO_QUOTA_API: 'errNoQuotaApi',
  NO_API_KEY: 'errNoApiKey',
  LOADING: 'loading',
  NOT_RUNNING: 'errNotRunning',
  UNSUPPORTED_OS: 'errUnsupportedOs',
  GROK_BILLING_BLOCKED: 'errGrokBillingBlocked',
}
function translateError(code, s) {
  const key = ERROR_KEYS[code]
  if (key) return s[key]
  return s.errOther + ': ' + (code || '?')
}

module.exports = { getStrings, resolveLang, translateError, fmt, DICTS }
